const repository = 'engasnm111/lnwjud';
const generatedFiles = new Set(['packages/capabilities/src/containment-integrity.generated.ts',
  'packages/capabilities/src/windows-capability-integrity.generated.ts', 'apps/desktop/src/main/update-worker-integrity.generated.ts']);
const controlRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
function refuse() { throw new Error('UPDATE_BUILDER_EVIDENCE_REFUSED'); }

export function builderContext(environment, credentialless = false) {
  if (environment.GITHUB_ACTIONS !== 'true' || environment.GITHUB_REPOSITORY !== repository || environment.GITHUB_EVENT_NAME !== 'push'
    || environment.GITHUB_REF !== 'refs/heads/main' || environment.GITHUB_REF_PROTECTED !== 'true'
    || environment.GITHUB_WORKFLOW_REF !== `${repository}/.github/workflows/ci.yml@refs/heads/main`
    || !/^[a-f0-9]{40}$/.test(environment.GITHUB_SHA) || !/^[a-f0-9]{40}$/.test(environment.LNWJUD_BUILDER_SHA)
    || !/^[1-9][0-9]{0,19}$/.test(environment.GITHUB_RUN_ID) || !/^[1-9][0-9]{0,19}$/.test(environment.GITHUB_RUN_ATTEMPT)) refuse();
  for (const [name, value] of Object.entries(environment)) {
    if (value && (/^(?:CSC_LINK|CSC_KEY_PASSWORD|WINDOWS_CSC_LINK|WINDOWS_CSC_KEY_PASSWORD|LNWJUD_UPDATE_RELEASE_PRIVATE_KEY_PEM)$/i.test(name)
      || credentialless && /^ACTIONS_ID_TOKEN_REQUEST_(?:URL|TOKEN)$/i.test(name))) refuse();
  }
  return { commit: environment.GITHUB_SHA, builderSha: environment.LNWJUD_BUILDER_SHA,
    runId: environment.GITHUB_RUN_ID, runAttempt: environment.GITHUB_RUN_ATTEMPT, ref: environment.GITHUB_REF };
}

export function assertGeneratedChanges(status) {
  for (const entry of status.split('\0').filter(Boolean)) {
    if (!entry.startsWith(' M ') || !generatedFiles.has(entry.slice(3))) refuse();
  }
}

export async function validateGeneratedIdentitySources(source) {
  const read = (relative, maximum) => readBoundedFile(path.join(source, relative), maximum);
  const helper = await read('apps/desktop/build/native-containment/lnwjud-containment.exe', 268435456n);
  const pin = await read('apps/desktop/build/native-containment/lnwjud-containment-pin.node', 16777216n);
  const runtime = await read('apps/desktop/build/native-containment/process-runtime.mjs', 16777216n);
  const worker = await read('apps/desktop/build/update-worker/lnwjud-update-worker.exe', 268435456n);
  const bridge = await read('packages/capabilities/src/windows-capability-bridge.ps1', 16777216n);
  const expected = {
    'packages/capabilities/src/containment-integrity.generated.ts':
      `export const CONTAINMENT_HELPER_SHA256 = '${helper.sha256}' as const;\nexport const CONTAINMENT_PIN_SHA256 = '${pin.sha256}' as const;\nexport const CONTAINMENT_RUNTIME_SHA256 = '${runtime.sha256}' as const;\n`,
    'apps/desktop/src/main/update-worker-integrity.generated.ts':
      `export const UPDATE_WORKER_SHA256 = '${worker.sha256}' as const;\nexport const UPDATE_WORKER_PIN_SHA256 = '${pin.sha256}' as const;\nexport const UPDATE_WORKER_BUILD_ID = 'lnwjud-update-worker-bootstrap-v1' as const;\nexport const UPDATE_WORKER_PROTOCOL = 1 as const;\n`,
    'packages/capabilities/src/windows-capability-integrity.generated.ts':
      `// Generated by apps/desktop/scripts/write-capability-integrity.mjs.\nexport const WINDOWS_CAPABILITY_BRIDGE_SHA256 = '${bridge.sha256}' as const;\nexport const WINDOWS_CAPABILITY_BRIDGE_SIZE_BYTES = ${bridge.sizeBytes} as const;\n`,
  };
  for (const [relative, text] of Object.entries(expected)) {
    const actual = await read(relative, 16384n);
    if (actual.bytes.toString('utf8').replaceAll('\r\n', '\n') !== text) refuse();
  }
}

export function validateProvenance(provenance, context) {
  if (provenance?.schemaVersion !== 1 || provenance.product !== 'lnwjud' || provenance.platform !== 'win32' || provenance.arch !== 'x64'
    || typeof provenance.version !== 'string' || !/^(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)$/.test(provenance.version)
    || provenance.version.length > 32 || provenance.version.split('.').some(part => BigInt(part) > 2147483647n)
    || provenance.source?.repository !== `https://github.com/${repository}` || provenance.source?.commit !== context.commit || provenance.source?.dirty !== false
    || provenance.build?.environment !== 'github-actions' || provenance.build?.runId !== context.runId || provenance.build?.runAttempt !== context.runAttempt
    || provenance.build?.ref !== context.ref || provenance.build?.signingCredentialConfigured !== false || !Array.isArray(provenance.artifacts)) refuse();
  const name = `lnwjud-Setup-${provenance.version}.exe`;
  const subjects = provenance.artifacts.filter(artifact => artifact?.name === name);
  if (subjects.length !== 1 || !/^[a-f0-9]{64}$/.test(subjects[0].sha256) || !Number.isSafeInteger(subjects[0].sizeBytes)
    || subjects[0].sizeBytes <= 0 || subjects[0].sizeBytes > 2147483648) refuse();
  return subjects[0];
}

async function readSubjectPair(directory, context) {
  const provenance = await readBoundedFile(path.join(directory, 'PROVENANCE.json'), 1048576n);
  const identity = validateProvenance(parseStrictJson(provenance.bytes, 1048576, 64), context);
  const artifact = await readBoundedFile(path.join(directory, identity.name), 2147483648n);
  if (artifact.sha256 !== identity.sha256 || artifact.sizeBytes !== String(identity.sizeBytes)) refuse();
  return { artifact: { ...artifact, name: identity.name }, provenance };
}

export async function inspectSubjectDirectory(directory, context, bundleNames = []) {
  const entries = await readdir(directory, { withFileTypes: true });
  const subjects = await readSubjectPair(directory, context);
  const expected = [subjects.artifact.name, 'PROVENANCE.json', ...bundleNames].sort();
  if (entries.some(entry => !entry.isFile()) || entries.map(entry => entry.name).sort().join('\0') !== expected.join('\0')) refuse();
  return subjects;
}

async function ordinaryDirectory(directory) {
  let current = path.resolve(directory);
  while (true) {
    const info = await lstat(current);
    if (!info.isDirectory() || info.isSymbolicLink()) refuse();
    const parent = path.dirname(current); if (parent === current) return;
    current = parent;
  }
}

function git(directory, args) {
  return execFileSync('git', args, { cwd: directory, encoding: 'utf8', windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] }).trimEnd();
}

async function trustedWorkspace(environment, context) {
  if (process.platform !== 'win32' || process.arch !== 'x64' || !path.isAbsolute(environment.GITHUB_WORKSPACE ?? '')) refuse();
  const workspace = path.resolve(environment.GITHUB_WORKSPACE);
  if (controlRoot !== path.join(workspace, '_trusted-builder') || git(controlRoot, ['rev-parse', 'HEAD']) !== context.builderSha
    || git(controlRoot, ['status', '--porcelain=v1', '--untracked-files=normal']) !== '') refuse();
  await ordinaryDirectory(workspace); await ordinaryDirectory(controlRoot);
  return workspace;
}

async function buildSubjects(environment) {
  const context = builderContext(environment, true);
  const workspace = await trustedWorkspace(environment, context); const source = path.join(workspace, '_source');
  await ordinaryDirectory(source);
  if (git(source, ['rev-parse', 'HEAD']) !== context.commit || git(source, ['status', '--porcelain=v1', '--untracked-files=normal']) !== '') refuse();
  const version = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8')).version;
  const powershell = path.join(environment.SystemRoot, 'System32/WindowsPowerShell/v1.0/powershell.exe');
  const result = spawnSync(powershell, ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', 'scripts/verify-release.ps1'],
    { cwd: source, env: { ...environment, GITHUB_WORKSPACE: source }, windowsHide: true, shell: false, stdio: 'inherit' });
  if (result.status !== 0 || result.error !== undefined || git(source, ['rev-parse', 'HEAD']) !== context.commit) refuse();
  assertGeneratedChanges(git(source, ['status', '--porcelain=v1', '-z', '--untracked-files=normal']));
  await validateGeneratedIdentitySources(source);
  const installers = path.join(source, 'apps/desktop/dist/installers'); const subjects = await readSubjectPair(installers, context);
  if (subjects.artifact.name !== `lnwjud-Setup-${version}.exe`) refuse();
  const output = path.join(workspace, '_subject-output'); await mkdir(output);
  for (const name of [subjects.artifact.name, 'PROVENANCE.json']) await copyFile(path.join(installers, name), path.join(output, name), constants.COPYFILE_EXCL);
  const copied = await inspectSubjectDirectory(output, context);
  if (copied.artifact.sha256 !== subjects.artifact.sha256 || copied.provenance.sha256 !== subjects.provenance.sha256) refuse();
}

async function retainBundles(environment, incoming, context) {
  const subjects = await inspectSubjectDirectory(incoming, context);
  if (subjects.artifact.sha256 !== environment.LNWJUD_EXPECTED_ARTIFACT_SHA256 || subjects.provenance.sha256 !== environment.LNWJUD_EXPECTED_PROVENANCE_SHA256
    || !path.isAbsolute(environment.RUNNER_TEMP ?? '')) refuse();
  const temporary = path.resolve(environment.RUNNER_TEMP);
  for (const [key, name] of [['LNWJUD_ARTIFACT_BUNDLE', 'artifact.bundle.json'], ['LNWJUD_PROVENANCE_BUNDLE', 'provenance.bundle.json']]) {
    if (typeof environment[key] !== 'string') refuse();
    const source = path.resolve(environment[key]); const relative = path.relative(temporary, source);
    if (relative === '' || relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) refuse();
    const bundle = await readBoundedFile(source, 16n * 1024n * 1024n);
    const parsed = parseStrictJson(bundle.bytes, 16 * 1024 * 1024, 64);
    if (parsed?.mediaType !== 'application/vnd.dev.sigstore.bundle.v0.3+json' || parsed.verificationMaterial === null || typeof parsed.verificationMaterial !== 'object'
      || parsed.dsseEnvelope === null || typeof parsed.dsseEnvelope !== 'object') refuse();
    const destination = path.join(incoming, name); await copyFile(source, destination, constants.COPYFILE_EXCL);
    if ((await readBoundedFile(destination, 16n * 1024n * 1024n)).sha256 !== bundle.sha256) refuse();
  }
  await inspectSubjectDirectory(incoming, context, ['artifact.bundle.json', 'provenance.bundle.json']);
}

export async function builderMain(mode, environment) {
  if (mode === 'build') { await buildSubjects(environment); return; }
  const context = builderContext(environment); const workspace = await trustedWorkspace(environment, context);
  const incoming = path.join(workspace, '_incoming'); await ordinaryDirectory(incoming);
  if (mode === 'bundles') { await retainBundles(environment, incoming, context); return; }
  if (mode !== 'inspect' || typeof environment.GITHUB_OUTPUT !== 'string') refuse();
  const subjects = await inspectSubjectDirectory(incoming, context);
  await appendFile(environment.GITHUB_OUTPUT, `artifact_name=${subjects.artifact.name}\nartifact_sha256=${subjects.artifact.sha256}\nprovenance_sha256=${subjects.provenance.sha256}\n`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { if (process.argv.length !== 3) refuse(); await builderMain(process.argv[2], process.env); }
  catch { process.stderr.write('UPDATE_BUILDER_EVIDENCE_REFUSED\n'); process.exitCode = 1; }
}
