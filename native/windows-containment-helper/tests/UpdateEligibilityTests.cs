using Lnwjud.UpdateWorker;
using System.Diagnostics;
using System.Security.Cryptography;
using System.Security.Principal;

namespace Lnwjud.Containment;

internal static class UpdateEligibilityTests
{
    internal static int Run()
    {
        var assertions = 0;
        void Check(bool value, string message) { assertions++; if (!value) throw new Exception(message); }
        void Refused(Action action, string reason)
        {
            try { action(); }
            catch (Refusal error) when (error.Reason == reason) { assertions++; return; }
            throw new Exception("Expected " + reason);
        }
        using var identity = WindowsIdentity.GetCurrent();
        var owner = identity.User?.Value ?? throw new Exception("No fixture owner");
        var boot = Guid.NewGuid().ToString("D");
        var nextBoot = Guid.NewGuid().ToString("D");
        var install = new string('a', 64);
        var root = Path.Combine(Path.GetTempPath(), "lnwjud-update-eligibility-" + Guid.NewGuid().ToString("N"));
        var paths = new List<string>();
        string NewRoot(string name) { var path = Path.Combine(root, name); paths.Add(path); return path; }
        try
        {
            var clean = NewRoot("clean");
            using (var store = new WindowsStoreIO(clean))
            {
                var admission = NativeUpdateEligibility.EnrollFixture(store, install, owner, boot);
                var initial = admission.Inspect(owner);
                Check(initial.Kind == "eligible" && initial.Writers == 0, "Trusted cold fixture epoch starts eligible");
                Refused(() => NativeUpdateEligibility.EnrollFixture(store, install, owner, boot), "UPDATE_ELIGIBILITY_ALREADY_ENROLLED");
                Refused(() => admission.Inspect("S-1-5-21-1234"), "UPDATE_ELIGIBILITY_OWNER_MISMATCH");
                var writer = admission.BeforeKnownWriterDispatch(owner);
                Refused(() => admission.Close(owner, initial.Position, Guid.NewGuid().ToString("D")), "UPDATE_ADMISSION_POSITION_CONFLICT");
                var executable = Environment.ProcessPath ?? throw new Exception("No test image");
                var jobName = @"Local\lnwjud-update-witness-" + Guid.NewGuid().ToString("N");
                var environment = Environment.GetEnvironmentVariables().Cast<System.Collections.DictionaryEntry>()
                    .ToDictionary(entry => (string)entry.Key, entry => (string)(entry.Value ?? ""), StringComparer.OrdinalIgnoreCase);
                using var child = ContainedProcess.Start(executable, ["installed-client-boundary-hold"], AppContext.BaseDirectory,
                    false, environment, jobName: jobName);
                var expected = new InstalledFile("fixture.exe", (ulong)new FileInfo(executable).Length,
                    Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(executable))).ToLowerInvariant());
                using var witness = NativeUpdateWriterWitness.CaptureFixture(writer, (int)child.ProcessId, jobName, executable, expected);
                Check(!witness.ObserveCessation(), "Live root and Job are not cessation");
                Refused(() => admission.CompleteKnownWriter(writer, witness), "UPDATE_WRITER_CESSATION_UNVERIFIED");
                Refused(() => NativeUpdateWriterWitness.CaptureFixture(writer, (int)child.ProcessId, jobName, executable,
                    expected with { Sha256 = new string('0', 64) }), "UPDATE_WRITER_IMAGE_MISMATCH");
                var transaction = Guid.NewGuid().ToString("D");
                admission.Close(owner, admission.Inspect(owner).Position, transaction);
                Refused(() => admission.BeforeOpaqueDispatch(owner), "UPDATE_ADMISSION_CLOSED");
                Refused(() => admission.BeforeKnownWriterDispatch(owner), "UPDATE_ADMISSION_CLOSED");
                Refused(() => admission.Seal(transaction), "UPDATE_ADMISSION_NOT_QUIESCENT");
                child.Cancel();
                var timer = Stopwatch.StartNew();
                while (!witness.ObserveCessation() && timer.Elapsed < TimeSpan.FromSeconds(5)) Thread.Sleep(10);
                Check(witness.ObserveCessation(), "Real stopped child and Job zero settle the retained native witness");
                admission.CompleteKnownWriter(writer, witness);
                var seal = admission.Seal(transaction);
                admission.RequireSeal(transaction, seal);
                Check(seal.Length == 64, "Seal is generated by native authority");
                Refused(() => admission.RequireSeal(transaction, new string('0', 64)), "UPDATE_ADMISSION_SEAL_INVALID");
                Refused(() => admission.RequireSeal(Guid.NewGuid().ToString("D"), seal), "UPDATE_ADMISSION_SEAL_INVALID");
            }
            using (var store = new WindowsStoreIO(clean))
            {
                var admission = NativeUpdateEligibility.OpenFixture(store, install, boot);
                Check(admission.Inspect(owner).Reason == "UPDATE_ADMISSION_CLOSED", "Sealed maintenance survives authority restart");
            }

            var opaque = NewRoot("opaque");
            using (var store = new WindowsStoreIO(opaque))
            {
                var admission = NativeUpdateEligibility.EnrollFixture(store, install, owner, boot);
                admission.BeforeOpaqueDispatch(owner);
                Check(admission.Inspect(owner).Reason == "UPDATE_UNBOUND_ACTIVITY_HISTORY", "Opaque target is stamped before any dispatch reply");
            }
            using (var store = new WindowsStoreIO(opaque))
            {
                var admission = NativeUpdateEligibility.OpenFixture(store, install, nextBoot);
                Check(admission.Inspect(owner).Reason == "UPDATE_UNBOUND_ACTIVITY_HISTORY", "Lost reply, caller death and reboot preserve unknown future-launch history");
                Refused(() => admission.StartColdEpoch(owner), "UPDATE_COLD_EPOCH_UNVERIFIED");
            }

            var bound = NewRoot("bound");
            using (var store = new WindowsStoreIO(bound))
            {
                var admission = NativeUpdateEligibility.EnrollFixture(store, install, owner, boot);
                _ = admission.BeforeKnownWriterDispatch(owner);
            }
            using (var store = new WindowsStoreIO(bound))
            {
                var admission = NativeUpdateEligibility.OpenFixture(store, install, boot);
                Check(admission.Inspect(owner).Reason == "UPDATE_WRITERS_ACTIVE_OR_UNKNOWN", "Authority restart does not clear a writer after lost launch reply");
                Refused(() => admission.StartColdEpoch(owner), "UPDATE_COLD_EPOCH_UNVERIFIED");
            }
            using (var store = new WindowsStoreIO(bound))
            {
                var admission = NativeUpdateEligibility.OpenFixture(store, install, nextBoot);
                admission.StartColdEpoch(owner);
                Check(admission.Inspect(owner).Kind == "eligible", "Only a new native boot can settle prior boot-bound first-party writers");
                admission.RecordUnboundHistory();
            }
            using (var store = new WindowsStoreIO(bound))
            {
                var admission = NativeUpdateEligibility.OpenFixture(store, install, Guid.NewGuid().ToString("D"));
                Refused(() => admission.StartColdEpoch(owner), "UPDATE_COLD_EPOCH_UNVERIFIED");
            }

            var pending = NewRoot("pending");
            using (var store = new WindowsStoreIO(pending))
            {
                _ = NativeUpdateEligibility.EnrollFixture(store, install, owner, boot);
                store.Stage("eligibility.pending.json", "{}"u8.ToArray());
            }
            using (var store = new WindowsStoreIO(pending))
                Refused(() => NativeUpdateEligibility.OpenFixture(store, install, boot), "UPDATE_ELIGIBILITY_PUBLICATION_PENDING");
            Check(File.ReadAllText(Path.Combine(pending, "eligibility.pending.json")) == "{}", "Refusal preserves interrupted publication for investigation");
            var nativeBoot = NativeBootIdentity.Read();
            Check(Guid.TryParseExact(nativeBoot, "D", out _) && NativeBootIdentity.Read() == nativeBoot, "Actual kernel boot identifier is stable within this boot");
            Console.WriteLine($"PASS native updater eligibility, cold-epoch refusals and exact writer cessation ({assertions} assertions)");
            return assertions;
        }
        finally
        {
            var expected = Path.Combine(Path.GetTempPath(), Path.GetFileName(root));
            if (!String.Equals(Path.GetFullPath(root), Path.GetFullPath(expected), StringComparison.OrdinalIgnoreCase)
                || !Path.GetFileName(root).StartsWith("lnwjud-update-eligibility-", StringComparison.Ordinal))
                throw new Exception("Fixture cleanup target changed");
            if (Directory.Exists(root)) Directory.Delete(root, true);
        }
    }
}
